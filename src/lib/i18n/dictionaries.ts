const dictionaries: Record<Locale, Dictionary> = { es, en };

export function getDictionary(lang: Locale): Dictionary {
  return dictionaries[lang];
}

/** Unidad de venta traducida ("pieza" → "each"); si no hay traducción se deja tal cual. */
export function unitLabel(dict: Dictionary, unit: string) {
  return dict.units[unit] ?? unit;
}
